/// DIFF-003: converts a raw ScrollBox `scrollTop` into the root-relative
/// viewport top that `visible_chunk_range` must consume. Upstream
/// (`component/patch-diff.tsx:164-181`) computes the chunk window inside the
/// virtual root's lifecycle pass:
///
/// ```text
/// const top = scroll.scrollTop - (root.y - scroll.content.y)
/// setFirst(Math.floor(top / VIRTUAL_CHUNK_LINES))
/// setLast(Math.floor((top + scroll.viewport.height) / VIRTUAL_CHUNK_LINES))
/// ```
///
/// `root.y` is the virtual root's absolute y in the same layout pass and
/// `scroll.content.y` is the scroll content's absolute y; their difference is
/// the root's scroll-independent offset inside the content, so the caller
/// MUST subtract it before chunking. A raw scrollTop double-counts that
/// offset and shifts the rendered window.
#[must_use]
pub fn relative_scroll_top(scroll_top: usize, root_y: i64, content_y: i64) -> usize {
    let offset = root_y - content_y;
    if offset <= 0 {
        scroll_top
    } else {
        scroll_top.saturating_sub(offset as usize)
    }
}

/// Inclusive chunk indexes rendered for a viewport, with one chunk of
/// overscan on each side (`patch-diff.tsx:164-181`). `scroll_top` MUST be the
/// root-relative value returned by `relative_scroll_top` (`patch-diff.tsx:168`
/// subtracts `root.y - scroll.content.y`); a raw ScrollBox scrollTop
/// double-counts the virtual root's content offset.
#[must_use]
pub fn visible_chunk_range(
    chunk_count: usize,
    scroll_top: usize,
    viewport_height: usize,
) -> (usize, usize) {
    if chunk_count == 0 {
        return (0, 0);
    }
    let first = scroll_top / VIRTUAL_CHUNK_LINES;
    let last = scroll_top.saturating_add(viewport_height) / VIRTUAL_CHUNK_LINES;
    (
        first.saturating_sub(1),
        last.saturating_add(1).min(chunk_count - 1),
    )
}

/// Placeholder height for an offscreen chunk (`patch-diff.tsx:180`).
#[must_use]
pub fn placeholder_height(chunk: &AddedPatchChunk) -> usize {
    chunk.rows
}

/// DIFF-003: the painted rows of one omitted virtual chunk — exactly
/// `chunk.rows` rows, not one marker row.
///
/// Upstream unmounts an offscreen chunk's content but the virtual box keeps
/// its height, so the row that follows it stays at the same absolute offset
/// (`component/patch-diff.tsx:164-181`). A single collapsed label would
/// shorten the body by `rows - 1` per omitted chunk and move every later
/// chunk, which makes a scroll offset point at the wrong diff row.
#[must_use]
pub fn placeholder_lines(chunk: &AddedPatchChunk) -> Vec<String> {
    let rows = placeholder_height(chunk);
    vec![format!("… {rows} lines …"); rows]
}

/// DIFF-003: exact row height of virtual chunk `index` in the split viewer.
/// The split surface virtualizes its already-painted rows in the same
/// `VIRTUAL_CHUNK_LINES` groups, so the final group is partial.
#[must_use]
pub fn split_chunk_height(total_rows: usize, index: usize) -> usize {
    total_rows
        .saturating_sub(index.saturating_mul(VIRTUAL_CHUNK_LINES))
        .min(VIRTUAL_CHUNK_LINES)
}

/// DIFF-003: the painted rows of one omitted split-viewer chunk, at exact
/// height. See [`placeholder_lines`] for why the height must not collapse.
#[must_use]
pub fn split_placeholder_lines(total_rows: usize, index: usize) -> Vec<String> {
    let rows = split_chunk_height(total_rows, index);
    vec![format!("… {rows} lines …"); rows]
}

