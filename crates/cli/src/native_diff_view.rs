/// Renders a patch as paired split rows. Headers span the full pane; context
/// lines appear on both sides; a change block pairs removed and added lines by
/// position, exactly like a unified hunk read column-wise.
#[must_use]
pub fn paint_rows_split(patch: &str, max_rows: usize, pane_width: usize) -> SplitPaintResult {
    let classified = classification_for_paint(patch);
    let inner = pane_width.saturating_sub(1);
    // DIFF-001: upstream `buildSplitView` gives each split side width="50%"
    // of the diff content box (@opentui/core 0.4.5 index.node.js:6056-6057)
    // and lets yoga resolve it. At an odd content width yoga rounds edge
    // positions half-up, so the left side's right edge (inner/2 = x.5) rounds
    // up: the LEFT pane receives the extra column (inner 9 -> left 5, right
    // 4). `inner` is the content box after the upstream 1-column diff padding
    // (index.tsx:3470 `paddingLeft={1}`, mirrored by `pane_width - 1`).
    let left_width = inner - inner / 2;
    let right_width = inner - left_width;
    let mut rows = Vec::new();
    let mut hit_cap = false;
    let mut index = 0usize;
    while index < classified.lines.len() {
        if rows.len() >= max_rows {
            hit_cap = true;
            break;
        }
        let line = &classified.lines[index];
        match line.role {
            DiffLineRole::Removed | DiffLineRole::Added => {
                let start = index;
                while index < classified.lines.len()
                    && matches!(
                        classified.lines[index].role,
                        DiffLineRole::Removed | DiffLineRole::Added
                    )
                {
                    index += 1;
                }
                let mut removed: Vec<&DiffLine> = Vec::new();
                let mut added: Vec<&DiffLine> = Vec::new();
                for change in &classified.lines[start..index] {
                    if change.role == DiffLineRole::Removed {
                        removed.push(change);
                    } else {
                        added.push(change);
                    }
                }
                for pair in 0..removed.len().max(added.len()) {
                    if rows.len() >= max_rows {
                        hit_cap = true;
                        break;
                    }
                    rows.push(SplitRow::Pair {
                        left: removed.get(pair).map(|line| split_cell(line)),
                        right: added.get(pair).map(|line| split_cell(line)),
                    });
                }
            }
            DiffLineRole::Context => {
                let old = line.old_line.map(|number| SplitCell {
                    line_number: Some(number),
                    sign: ' ',
                    text: line.content.clone(),
                    role: DiffLineRole::Context,
                });
                let new = line.new_line.map(|number| SplitCell {
                    line_number: Some(number),
                    sign: ' ',
                    text: line.content.clone(),
                    role: DiffLineRole::Context,
                });
                rows.push(SplitRow::Pair { left: old, right: new });
                index += 1;
            }
            _ => {
                rows.push(SplitRow::Full(line.clone()));
                index += 1;
            }
        }
    }
    SplitPaintResult {
        rows,
        left_width,
        right_width,
        truncated: classified.truncated || hit_cap,
        malformed: classified.malformed,
    }
}

/// One hunk of a patch, as `PatchDiff` renders it (`util/diff.ts:40-54`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PatchHunkView {
    /// The `@@ ... @@` header line, present for hunks after the first.
    pub header: Option<String>,
    /// The hunk patch including the file prefix, ready for a diff renderable.
    pub patch: String,
    /// Renderable rows (paired change runs count once).
    pub rows: usize,
    /// `patch-diff.tsx:79-85` paints a full-width header band before every
    /// hunk after the first. Upstream has no scroll-pinned header in the
    /// pinned revision (its `sticky*` options belong to scroll boxes), so this
    /// is the hunk band, not a sticky overlay.
    pub band_before: bool,
}

/// Splits a patch into hunk views. A patch with zero or one hunk header is
/// returned as a single view, exactly like `splitPatchHunks`.
#[must_use]
pub fn split_patch_hunks(patch: &str) -> Vec<PatchHunkView> {
    let starts = hunk_header_starts(patch);
    if starts.len() <= 1 {
        return vec![PatchHunkView {
            header: None,
            patch: patch.to_string(),
            rows: starts.first().map_or(0, |&start| split_rows(&patch[start..])),
            band_before: false,
        }];
    }
    let prefix = &patch[..starts[0]];
    starts
        .iter()
        .enumerate()
        .map(|(index, &start)| {
            let end = starts.get(index + 1).copied().unwrap_or(patch.len());
            let line_end = patch[start..].find('\n').map(|offset| start + offset);
            let header_end = line_end.unwrap_or(end);
            let header = patch[start..header_end].to_string();
            PatchHunkView {
                header: Some(header),
                patch: format!("{prefix}{}", &patch[start..end]),
                rows: split_rows(&patch[start..end]),
                band_before: index > 0,
            }
        })
        .collect()
}

fn hunk_header_starts(patch: &str) -> Vec<usize> {
    let mut starts = Vec::new();
    let mut offset = 0usize;
    for line in patch.split_inclusive('\n') {
        if is_hunk_header_at(line.as_bytes()) {
            starts.push(offset);
        }
        offset += line.len();
    }
    starts
}

/// `util/diff.ts:56-84`: context rows count once, `\` markers do not count,
/// and a removed/added run counts `max(deletions, additions)`.
fn split_rows(hunk: &str) -> usize {
    let lines: Vec<&str> = hunk
        .strip_suffix('\n')
        .unwrap_or(hunk)
        .split('\n')
        .skip(1)
        .collect();
    let mut rows = 0usize;
    let mut index = 0usize;
    while index < lines.len() {
        let prefix = lines[index].chars().next();
        match prefix {
            Some(' ') | None => {
                rows += 1;
                index += 1;
            }
            Some('\\') => index += 1,
            _ => {
                let mut additions = 0usize;
                let mut deletions = 0usize;
                while index < lines.len() {
                    match lines[index].chars().next() {
                        Some('+') => additions += 1,
                        Some('-') => deletions += 1,
                        _ => break,
                    }
                    index += 1;
                }
                rows += additions.max(deletions);
            }
        }
    }
    rows
}

/// DIFF-003: one bounded lexical source span transported with a live diff
/// chunk. `flags` carries the same `SYN_*` bits as the Markdown code painter
/// (`markdown_runs::code_token_cell_spans`), so a native painter reuses that
/// existing theme mapping instead of inventing a second one.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct DiffHighlightSpan {
    /// Inclusive display-cell start inside the rendered row. The row is
    /// `+<source>` (`util/diff.ts:18-38` keeps the sign), so the sign occupies
    /// cell 0 and a source token at cell `n` starts at `n + 1`.
    pub start: u16,
    /// Exclusive display-cell end on the same row.
    pub end: u16,
    /// One `markdown_runs::SYN_*` class bit for `[start, end)`.
    pub flags: u32,
}

/// A chunk of an added-file patch (`util/diff.ts:7-11,18-38`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct AddedPatchChunk {
    pub patch: String,
    pub lines: Vec<String>,
    pub rows: usize,
    /// DIFF-003: source language inferred from the added-file path. `None`
    /// preserves plain rendering when the patch carries no usable source
    /// path, and it suppresses token spans for the whole chunk set.
    pub filetype: Option<String>,
    /// DIFF-003: bounded lexical spans for exactly [`Self::rows`] rows, in
    /// the same order as [`Self::lines`]. Each entry is sorted and disjoint
    /// over the rendered row; every entry is empty when [`Self::filetype`] is
    /// `None`.
    pub highlight_spans: Vec<Vec<DiffHighlightSpan>>,
}

/// Splits a new-file patch into `size`-line chunks. Returns `None` for
/// anything with context or removed lines.
#[must_use]
pub fn split_added_patch(patch: &str, size: usize) -> Option<Vec<AddedPatchChunk>> {
    if size == 0 {
        return None;
    }
    let (header_start, header_end, count) = find_new_file_header(patch)?;
    let body = &patch[header_end..];
    let body = body.strip_suffix('\n').unwrap_or(body);
    let mut lines: Vec<String> = body.split('\n').map(str::to_string).collect();
    let marker = match lines.last() {
        Some(line) if line.starts_with("\\ No newline at end of file") => lines.pop(),
        _ => None,
    };
    if lines.len() != count || lines.iter().any(|line| !line.starts_with('+')) {
        return None;
    }
    let prefix = &patch[..header_start];
    // DIFF-003: the language belongs to the file header, not to a chunk, so
    // resolve it once and transport it on every chunk. Spans are computed
    // over the whole added file before slicing, then carried per chunk, so a
    // later chunk keeps the same highlighting it has in the full body.
    let filetype = added_filetype(prefix);
    let whole_file_spans = added_file_highlights(&lines, filetype.as_deref());
    let chunk_count = count.div_ceil(size);
    Some(
        (0..chunk_count)
            .map(|index| {
                let start = index * size;
                let slice: Vec<String> = lines
                    .iter()
                    .skip(start)
                    .take(size)
                    .cloned()
                    .collect();
                let suffix = match &marker {
                    Some(marker) if start + size >= count => format!("\n{marker}"),
                    _ => String::new(),
                };
                AddedPatchChunk {
                    patch: format!(
                        "{prefix}@@ -0,0 +{},{} @@\n{}{suffix}",
                        start + 1,
                        slice.len(),
                        slice.join("\n")
                    ),
                    rows: slice.len(),
                    lines: slice,
                    filetype: filetype.clone(),
                    highlight_spans: whole_file_spans
                        .iter()
                        .skip(start)
                        .take(size)
                        .cloned()
                        .collect(),
                }
            })
            .collect(),
    )
}

/// DIFF-003: resolves the added side's source language from the patch header
/// — everything before the first `@@` hunk header, which is the only region
/// that can contain a real `+++ ` file line. `+++ b/<path>` names the new
/// file; a `/dev/null` destination carries no added-file language.
fn added_filetype(header: &str) -> Option<String> {
    let path = header.lines().find_map(|line| line.strip_prefix("+++ "))?.trim();
    let path = path.strip_prefix("b/").unwrap_or(path);
    if path.is_empty() || path == "/dev/null" {
        return None;
    }
    let extension = std::path::Path::new(path)
        .extension()?
        .to_str()?
        .to_ascii_lowercase();
    let language = match extension.as_str() {
        "c" => "c",
        "cc" | "cpp" | "cxx" | "h" | "hpp" => "cpp",
        "css" => "css",
        "dart" => "dart",
        "go" => "go",
        "html" | "htm" => "html",
        "java" => "java",
        "js" | "jsx" | "mjs" | "cjs" => "javascript",
        "json" => "json",
        "kt" | "kts" => "kotlin",
        "lua" => "lua",
        "php" => "php",
        "py" => "python",
        "rb" => "ruby",
        "rs" => "rust",
        "scala" => "scala",
        "sh" | "bash" | "zsh" => "shell",
        "sql" => "sql",
        "swift" => "swift",
        "toml" => "toml",
        "ts" | "tsx" | "mts" | "cts" => "typescript",
        "yaml" | "yml" => "yaml",
        _ => return None,
    };
    Some(language.to_owned())
}

/// DIFF-003: whole-file lexical spans, one row-relative entry per added line.
/// An unresolved language keeps every row plain rather than guessing a
/// grammar the shared tokenizer was not registered for.
fn added_file_highlights(lines: &[String], filetype: Option<&str>) -> Vec<Vec<DiffHighlightSpan>> {
    if filetype.is_none() {
        // No resolved language: keep one empty entry per row so the chunk
        // slice stays row-aligned with `lines`.
        return vec![Vec::new(); lines.len()];
    }
    let mut spans = Vec::with_capacity(lines.len());
    for line in lines {
        spans.push(added_row_highlights(line));
    }
    spans
}

/// DIFF-003: token spans for one rendered `+<source>` row.
fn added_row_highlights(row: &str) -> Vec<DiffHighlightSpan> {
    let Some(source) = row.strip_prefix('+') else {
        return Vec::new();
    };
    crate::markdown_runs::code_token_cell_spans(source)
        .into_iter()
        .filter_map(|(start, end, flags)| {
            // The rendered row keeps the `+` sign, so a source token at cell
            // `n` paints at row cell `n + 1`. Spans outside the `u16` wire
            // range are dropped instead of being clamped onto a wrong cell.
            let start = u16::try_from(start.saturating_add(1)).ok()?;
            let end = u16::try_from(end.saturating_add(1)).ok()?;
            (start < end).then_some(DiffHighlightSpan { start, end, flags })
        })
        .collect()
}

fn find_new_file_header(patch: &str) -> Option<(usize, usize, usize)> {
    let prefix = "@@ -0,0 +1,";
    let mut offset = 0usize;
    for line in patch.split_inclusive('\n') {
        if line.ends_with('\n') && line.starts_with(prefix) {
            let rest = &line[prefix.len()..];
            let digits = rest.bytes().take_while(u8::is_ascii_digit).count();
            if digits > 0 && rest[digits..].starts_with(" @@") {
                let count = rest[..digits].parse::<usize>().ok()?;
                return Some((offset, offset + line.len(), count));
            }
        }
        offset += line.len();
    }
    None
}

