#![forbid(unsafe_code)]
//! Native diff view model v3: multi-file unified-diff classification.
//!
//! V2 fixes plus:
//! - No-newline marker (`\`) retained after exact hunk counts via pre-check
//! - G4 count validation at end of every hunk (malformed indicator, not false success)
//! - Distinct `malformed` flag separate from resource `truncated`
//!
//! Pure state: no rendering, no IO, no threads, no FFI. Std only.

pub const MAX_DIFF_PATCH_BYTES: usize = 64 * 1024;
pub const MAX_DIFF_LINES: usize = 4096;
pub const MAX_HUNKS: usize = 256;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DiffLineRole {
    HunkHeader,
    Added,
    Removed,
    Context,
    NoNewline,
    FileHeader,
    DiffHeader,
    Blank,
}

/// Semantic paint roles consumed by the native renderer.  Keeping these as
/// metadata (rather than selecting RGB values here) lets the caller apply the
/// active theme while still preserving the upstream distinction between line
/// content, signs, hunk headers, and the two colored gutters.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DiffColorRole {
    Context,
    Added,
    Removed,
    HunkHeader,
    FileHeader,
    DiffHeader,
    NoNewline,
    Blank,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DiffLine {
    pub role: DiffLineRole,
    pub content: String,
    pub old_line: Option<u32>,
    pub new_line: Option<u32>,
    pub hunk_index: usize,
    pub line_index: usize,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ClassifiedPatch {
    pub lines: Vec<DiffLine>,
    pub truncated: bool,
    pub malformed: bool,
    pub consumed_bytes: usize,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DiffPaintRow {
    pub role: DiffLineRole,
    pub old_line: Option<u32>,
    pub new_line: Option<u32>,
    pub text: String,
    /// Content/background semantic role (not an RGB value).
    pub color: DiffColorRole,
    /// Gutter semantic role. Added/removed rows use their corresponding
    /// line-number background; all other rows use the context gutter.
    pub line_number_color: DiffColorRole,
    /// Number of columns reserved for each side of the line-number gutter.
    pub line_number_width: usize,
    /// True for a continuation generated by wrapping a logical diff line.
    pub continuation: bool,
    /// Zero-based hunk ordinal. Upstream `PatchDiff` paints a hunk-header band
    /// only for hunks after the first (`<Show when={index() > 0}>`,
    /// `packages/tui/src/component/patch-diff.tsx:79`), and a single-hunk diff
    /// carries no `header` at all (`util/diff.ts:57-59`); consumers skip the
    /// header row when this is 0.
    pub hunk_index: usize,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PaintResult {
    pub rows: Vec<DiffPaintRow>,
    pub truncated: bool,
    pub malformed: bool,
}

#[must_use]
pub fn paint_rows(patch: &str, max_rows: usize) -> PaintResult {
    let classified = classify_patch(patch);
    let total_input_lines = classified.lines.len();
    let mut rows = Vec::with_capacity(classified.lines.len().min(max_rows));
    let mut row_count = 0usize;
    for line in classified.lines.into_iter() {
        if row_count >= max_rows { break; }
        let text = match line.role {
            DiffLineRole::Added => format!("+{}", line.content),
            DiffLineRole::Removed => format!("-{}", line.content),
            DiffLineRole::Context => format!(" {}", line.content),
            DiffLineRole::NoNewline => format!("\\{}", line.content),
            DiffLineRole::FileHeader => line.content.clone(),
            DiffLineRole::DiffHeader => line.content.clone(),
            _ => line.content.clone(),
        };
        rows.push(make_paint_row(&line, text, 0, false));
        row_count += 1;
    }
    PaintResult {
        rows,
        truncated: classified.truncated || row_count < total_input_lines,
        malformed: classified.malformed,
    }
}

#[must_use]
pub fn paint_rows_with_gutter(patch: &str, max_rows: usize) -> PaintResult {
    let classified = classification_for_paint(patch);
    let total_input_lines = classified.lines.len();
    let (padding, digits) = gutter_width(&classified.lines, 0);
    let mut rows = Vec::with_capacity(classified.lines.len().min(max_rows));
    let mut row_count = 0usize;
    for line in classified.lines.into_iter() {
        if row_count >= max_rows { break; }
        let text = match line.role {
            DiffLineRole::Added => format!("+{}", line.content),
            DiffLineRole::Removed => format!("-{}", line.content),
            DiffLineRole::Context => format!(" {}", line.content),
            DiffLineRole::NoNewline => format!("\\{}", line.content),
            DiffLineRole::FileHeader => line.content.clone(),
            DiffLineRole::DiffHeader => line.content.clone(),
            _ => line.content.clone(),
        };
        let old = line.old_line.map(|n| n.to_string()).unwrap_or_default();
        let new = line.new_line.map(|n| n.to_string()).unwrap_or_default();
        let gutter = format!("{:padding$} {:>digits$} {:>digits$} ", "", old, new, padding = padding, digits = digits);
        rows.push(make_paint_row(&line, format!("{gutter}{text}"), digits, false));
        row_count += 1;
    }
    PaintResult {
        rows,
        truncated: classified.truncated || row_count < total_input_lines,
        malformed: classified.malformed,
    }
}

/// Paint rows with the same word wrapping used by the interactive diff
/// surfaces. The existing `paint_rows_with_gutter` remains the unbounded-width
/// compatibility API; callers that know their measured pane width should use
/// this function so continuation rows retain style metadata and blank gutters.
#[must_use]
pub fn paint_rows_with_gutter_wrapped(patch: &str, max_rows: usize, width: usize) -> PaintResult {
    let classified = classification_for_paint(patch);
    let (_, digits) = gutter_width(&classified.lines, 0);
    let gutter_len = 1usize.saturating_add(digits.saturating_mul(2)).saturating_add(3);
    let content_width = width.saturating_sub(gutter_len).max(1);
    let mut rows = Vec::with_capacity(classified.lines.len().min(max_rows));
    let mut row_cap_reached = false;

    for line in classified.lines.iter() {
        if rows.len() >= max_rows { row_cap_reached = true; break; }
        let body = match line.role {
            DiffLineRole::Added => format!("+{}", line.content),
            DiffLineRole::Removed => format!("-{}", line.content),
            DiffLineRole::Context => format!(" {}", line.content),
            DiffLineRole::NoNewline => format!("\\{}", line.content),
            _ => line.content.clone(),
        };
        let chunks = wrap_diff_text(&body, content_width);
        for (chunk_index, chunk) in chunks.into_iter().enumerate() {
            if rows.len() >= max_rows { row_cap_reached = true; break; }
            let gutter = if chunk_index == 0 {
                let old = line.old_line.map(|n| n.to_string()).unwrap_or_default();
                let new = line.new_line.map(|n| n.to_string()).unwrap_or_default();
                format!("{:padding$} {:>digits$} {:>digits$} ", "", old, new, padding = 1, digits = digits)
            } else { " ".repeat(gutter_len) };
            let continuation = chunk_index != 0;
            let mut row = make_paint_row(line, format!("{gutter}{chunk}"), digits, continuation);
            if continuation {
                row.old_line = None;
                row.new_line = None;
            }
            rows.push(row);
        }
    }
    PaintResult {
        rows,
        truncated: classified.truncated || row_cap_reached,
        malformed: classified.malformed,
    }
}

fn make_paint_row(line: &DiffLine, text: String, line_number_width: usize, continuation: bool) -> DiffPaintRow {
    let color = match line.role {
        DiffLineRole::Added => DiffColorRole::Added,
        DiffLineRole::Removed => DiffColorRole::Removed,
        DiffLineRole::Context => DiffColorRole::Context,
        DiffLineRole::HunkHeader => DiffColorRole::HunkHeader,
        DiffLineRole::FileHeader => DiffColorRole::FileHeader,
        DiffLineRole::DiffHeader => DiffColorRole::DiffHeader,
        DiffLineRole::NoNewline => DiffColorRole::NoNewline,
        DiffLineRole::Blank => DiffColorRole::Blank,
    };
    let line_number_color = match line.role {
        DiffLineRole::Added => DiffColorRole::Added,
        DiffLineRole::Removed => DiffColorRole::Removed,
        _ => DiffColorRole::Context,
    };
    DiffPaintRow { role: line.role, old_line: line.old_line, new_line: line.new_line, text, color, line_number_color, line_number_width, continuation, hunk_index: line.hunk_index }
}

fn wrap_diff_text(text: &str, width: usize) -> Vec<String> {
    if text.is_empty() { return vec![String::new()]; }
    let width = width.max(1);
    let mut clusters: Vec<(String, usize)> = Vec::new();
    crate::native_view_layout::visit_unpadded_cells(text, usize::MAX, |glyph, cells| {
        clusters.push((glyph.to_owned(), cells));
    });
    if clusters.is_empty() { return vec![String::new()]; }
    let mut result = Vec::new();
    let mut row = String::new();
    let mut used = 0usize;
    for (glyph, cells) in clusters {
        if used > 0 && used.saturating_add(cells) > width {
            result.push(std::mem::take(&mut row));
            used = 0;
        }
        row.push_str(&glyph);
        used = used.saturating_add(cells);
    }
    if !row.is_empty() { result.push(row); }
    result
}

#[must_use]
pub fn paint_rows_simple(patch: &str, max_rows: usize) -> Vec<DiffPaintRow> {
    paint_rows(patch, max_rows).rows
}

pub fn classify_patch(patch: &str) -> ClassifiedPatch {
    let bytes = patch.as_bytes();
    let byte_cap_reached = bytes.len() > MAX_DIFF_PATCH_BYTES;
    let end = if byte_cap_reached { MAX_DIFF_PATCH_BYTES } else { bytes.len() };
    let end = snap_to_char_boundary(patch, end);
    let input = &patch[..end];

    let hunk_starts = find_hunk_starts(input);
    let mut lines: Vec<DiffLine> = Vec::with_capacity(hunk_starts.len().min(MAX_HUNKS).saturating_mul(8));
    let mut truncated = byte_cap_reached;
    let mut malformed = false;

    // Prefix region: before first @@ — classify ---/+++ as FileHeader,
    // diff --git/index as DiffHeader.
    let prefix_end = hunk_starts.first().copied().unwrap_or(input.len());
    for raw in input[..prefix_end].split('\n').filter(|l| !l.is_empty()) {
        if lines.len() >= MAX_DIFF_LINES { truncated = true; break; }
        let role = classify_prefix_line(raw);
        lines.push(DiffLine {
            role,
            content: raw.to_string(),
            old_line: None,
            new_line: None,
            hunk_index: 0,
            line_index: lines.len(),
        });
    }

    for (hunk_idx, &start) in hunk_starts.iter().enumerate() {
        if hunk_idx >= MAX_HUNKS {
            truncated = true;
            break;
        }
        let hunk_end = hunk_starts.get(hunk_idx + 1).copied().unwrap_or(input.len());
        let hunk_text = &input[start..hunk_end];
        if let Some(ranges) = parse_hunk_header(hunk_text) {
            let (old_start, old_count, new_start, new_count) = ranges;
            let mut old_line = old_start;
            let mut new_line = new_start;
            let mut old_consumed: u32 = 0;
            let mut new_consumed: u32 = 0;

            let header_end = hunk_text.find('\n').unwrap_or(hunk_text.len());
            let header_line = &hunk_text[..header_end];

            if lines.len() < MAX_DIFF_LINES {
                lines.push(DiffLine {
                    role: DiffLineRole::HunkHeader,
                    content: header_line.to_string(),
                    old_line: None,
                    new_line: None,
                    hunk_index: hunk_idx,
                    line_index: lines.len(),
                });
            }

            let body = if header_end < hunk_text.len() { &hunk_text[header_end + 1..] } else { "" };
            let body_lines: Vec<&str> = split_diff_lines(body);
            let mut b_line_index = 1usize;
            let mut inter_hunk = false;

            for &raw_line in &body_lines {
                if lines.len() >= MAX_DIFF_LINES {
                    truncated = true;
                    break;
                }

                // No-newline marker is ALWAYS part of hunk body, checked first
                // (V2 fix for t03/e06: marker retained after exact counts).
                let is_no_newline = !raw_line.is_empty() && raw_line.as_bytes()[0] == b'\\';

                // Exhausted counts alone do not turn an extra body line into
                // metadata. Preserve its visible role/number, but flag the
                // invalid count below. An actual header ends the body after
                // the declared range; later header rows stay outside it.
                let header_role = classify_prefix_line(raw_line);
                if old_consumed >= old_count && new_consumed >= new_count
                    && matches!(header_role, DiffLineRole::FileHeader | DiffLineRole::DiffHeader)
                {
                    inter_hunk = true;
                }
                let in_body = is_no_newline || !inter_hunk;

                let (role, content, inc_old, inc_new) = if in_body {
                    classify_hunk_body_line(raw_line)
                } else {
                    // Inter-hunk: --- / +++ are FileHeader, not Removed/Added.
                    (classify_prefix_line(raw_line), raw_line, false, false)
                };

                lines.push(DiffLine {
                    role,
                    content: content.to_string(),
                    old_line: if inc_old { Some(old_line) } else { None },
                    new_line: if inc_new { Some(new_line) } else { None },
                    hunk_index: hunk_idx,
                    line_index: b_line_index,
                });

                if inc_old {
                    if old_consumed >= old_count { malformed = true; }
                    old_consumed = old_consumed.saturating_add(1);
                    old_line = old_line.saturating_add(1);
                }
                if inc_new {
                    if new_consumed >= new_count { malformed = true; }
                    new_consumed = new_consumed.saturating_add(1);
                    new_line = new_line.saturating_add(1);
                }
                b_line_index += 1;
            }

            // G4: validate hunk body line counts against declared ranges.
            // Mismatched counts indicate malformed diff, not resource truncation.
            if old_consumed != old_count || new_consumed != new_count {
                malformed = true;
            }
        }
        if truncated { break; }
    }

    ClassifiedPatch {
        lines,
        truncated,
        malformed,
        consumed_bytes: end,
    }
}

fn split_diff_lines(s: &str) -> Vec<&str> {
    let ends_with_newline = s.ends_with('\n');
    s.split('\n')
        .filter(|l| !l.is_empty() || !ends_with_newline)
        .map(|l| l.strip_suffix('\r').unwrap_or(l))
        .collect()
}

/// FFI-08: which classifier produced the paint classification for a patch.
///
/// `Bridge` means `opentui_bridge::diff::FilePatch::parse` upstream
/// (`packages/core/src/renderables/Diff.ts:1-120`) classified the hunk rows;
/// `Local` means the tolerant legacy classifier below did.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DiffClassifierSource {
    Bridge,
    Local,
}

/// FFI-08 consumer entry: the classification actually used by the inline
/// gutter/split paint pipeline. Patches the upstream parser accepts are
/// classified by the bridge producer; anything it rejects (byte cap,
/// `\ No newline` markers, bare/inter-hunk body lines, count drift, hunk
/// overflow) keeps the byte-identical legacy classification.
#[must_use]
pub fn classify_patch_for_paint(patch: &str) -> ClassifiedPatch {
    bridge_classified(patch).unwrap_or_else(|| classify_patch(patch))
}

/// Which source `classify_patch_for_paint` selects (test observe seam).
#[must_use]
pub fn classifier_source(patch: &str) -> DiffClassifierSource {
    if bridge_classified(patch).is_some() {
        DiffClassifierSource::Bridge
    } else {
        DiffClassifierSource::Local
    }
}

#[must_use]
fn classification_for_paint(patch: &str) -> ClassifiedPatch {
    classify_patch_for_paint(patch)
}

/// Bridge-backed classification: returns `None` whenever the upstream
/// `FilePatch::parse` producer cannot classify the patch under the exact
/// legacy contract, keeping paint output byte-identical to
/// `classify_patch`.
fn bridge_classified(patch: &str) -> Option<ClassifiedPatch> {
    use opencode_rk_opentui_bridge::diff::{FilePatch, RowKind};

    let bytes = patch.as_bytes();
    // Legacy byte cap and `\ No newline` markers (folded into the previous
    // row by the bridge producer, emitted as their own paint row locally)
    // keep the legacy classifier.
    if bytes.len() > MAX_DIFF_PATCH_BYTES || bytes.contains(&b'\\') {
        return None;
    }
    let hunk_starts = find_hunk_starts(patch);
    // No hunks means the legacy prefix-only path; > MAX_HUNKS means the
    // legacy `truncated` flag must be set by the legacy loop itself.
    if hunk_starts.is_empty() || hunk_starts.len() > MAX_HUNKS {
        return None;
    }

    // Every body/inter-hunk line after the first hunk start must carry a
    // unified marker (' ', '+', '-' or be empty). The legacy classifier
    // paints bare body lines as `Blank` rows without consuming line
    // numbers; the bridge producer folds them into `Context`, so such
    // patches stay local.
    for (hunk_idx, &start) in hunk_starts.iter().enumerate() {
        let end = hunk_starts.get(hunk_idx + 1).copied().unwrap_or(patch.len());
        let region = &patch[start..end];
        let (header, body) = match region.split_once('\n') {
            Some((header, body)) => (header, body),
            None => (region, ""),
        };
        // The legacy classifier keeps the trailing `\r` on hunk-header rows
        // (`header_line = &hunk_text[..header_end]`), while the bridge
        // producer strips it, so a CRLF header would diverge (FFI-08).
        if header.ends_with('\r') {
            return None;
        }
        for line in body.split('\n') {
            let line = line.strip_suffix('\r').unwrap_or(line);
            // Inter-hunk `--- `/`+++ ` separators of a multi-file patch are
            // `FileHeader` rows for the legacy classifier; the bridge
            // producer would swallow them as path headers and drop the two
            // painted rows, so they stay local (FFI-08).
            if line.starts_with("---") || line.starts_with("+++") {
                return None;
            }
            match line.as_bytes().first() {
                None | Some(b' ') | Some(b'+') | Some(b'-') => {}
                _ => return None,
            }
        }
    }

    // Feed the producer only the hunk region: the `---`/`+++` preamble stays
    // in the locally classified prefix exactly like `classify_patch`.
    let parsed = FilePatch::parse(&patch[hunk_starts[0]..]).ok()?;

    // Upstream strictness plus a declared-count check: the bridge producer
    // does not reject count drift, but legacy flags it `malformed`, so any
    // drift falls back.
    for hunk in parsed.hunks() {
        let mut old_seen = 0u32;
        let mut new_seen = 0u32;
        for row in &parsed.rows()[hunk.first_row()..hunk.end_row()] {
            if row.kind() != RowKind::Added {
                old_seen += 1;
            }
            if row.kind() != RowKind::Removed {
                new_seen += 1;
            }
        }
        if old_seen != hunk.old_count() || new_seen != hunk.new_count() {
            return None;
        }
    }

    let prefix_end = hunk_starts[0];
    let mut lines: Vec<DiffLine> = Vec::with_capacity(parsed.rows().len() + hunk_starts.len());
    for raw in patch[..prefix_end].split('\n').filter(|l| !l.is_empty()) {
        lines.push(DiffLine {
            role: classify_prefix_line(raw),
            content: raw.to_string(),
            old_line: None,
            new_line: None,
            hunk_index: 0,
            line_index: lines.len(),
        });
    }
    let mut pushed_hunks = 0usize;
    let mut body_ordinal = 1usize;
    let mut push_hunk_header = |lines: &mut Vec<DiffLine>, hunk_header: &str, hunk_index: usize| {
        lines.push(DiffLine {
            role: DiffLineRole::HunkHeader,
            content: hunk_header.to_string(),
            old_line: None,
            new_line: None,
            hunk_index,
            line_index: lines.len(),
        });
    };
    for row in parsed.rows() {
        let hunk_index = usize::from(row.hunk());
        while pushed_hunks <= hunk_index {
            push_hunk_header(
                &mut lines,
                parsed.hunks()[pushed_hunks].header(),
                pushed_hunks,
            );
            pushed_hunks += 1;
            body_ordinal = 1;
        }
        let role = match row.kind() {
            RowKind::Context => DiffLineRole::Context,
            RowKind::Added => DiffLineRole::Added,
            RowKind::Removed => DiffLineRole::Removed,
        };
        lines.push(DiffLine {
            role,
            content: row.text().to_string(),
            old_line: row.old_line(),
            new_line: row.new_line(),
            hunk_index,
            line_index: body_ordinal,
        });
        body_ordinal += 1;
    }
    // Trailing hunks that declare zero rows still paint their header band.
    while pushed_hunks < parsed.hunks().len() {
        push_hunk_header(
            &mut lines,
            parsed.hunks()[pushed_hunks].header(),
            pushed_hunks,
        );
        pushed_hunks += 1;
    }
    if lines.len() > MAX_DIFF_LINES {
        return None; // legacy truncation contract stays with classify_patch
    }
    Some(ClassifiedPatch {
        lines,
        truncated: false,
        malformed: false,
        consumed_bytes: bytes.len(),
    })
}

fn classify_prefix_line(line: &str) -> DiffLineRole {
    if line.starts_with("---") {
        DiffLineRole::FileHeader
    } else if line.starts_with("+++") {
        DiffLineRole::FileHeader
    } else if line.starts_with("diff --git")
        || line.starts_with("index ")
        || line.starts_with("new file")
        || line.starts_with("deleted file")
        || line.starts_with("old mode")
        || line.starts_with("new mode")
        || line.starts_with("similarity index")
        || line.starts_with("dissimilarity index")
        || line.starts_with("rename from")
        || line.starts_with("rename to")
        || line.starts_with("copy from")
        || line.starts_with("copy to") {
        DiffLineRole::DiffHeader
    } else {
        DiffLineRole::Blank
    }
}

fn classify_hunk_body_line(line: &str) -> (DiffLineRole, &str, bool, bool) {
    if line.is_empty() {
        return (DiffLineRole::Context, "", true, true);
    }
    let first = line.as_bytes()[0];
    match first {
        b'+' => (DiffLineRole::Added, &line[1..], false, true),
        b'-' => (DiffLineRole::Removed, &line[1..], true, false),
        b'\\' => (DiffLineRole::NoNewline, &line[1..], false, false),
        b' ' => (DiffLineRole::Context, &line[1..], true, true),
        _ => (DiffLineRole::Blank, line, false, false),
    }
}

fn find_hunk_starts(input: &str) -> Vec<usize> {
    let mut starts = Vec::with_capacity(MAX_HUNKS.saturating_add(1));
    let bytes = input.as_bytes();
    let mut i = 0;
    while i + 1 < bytes.len() {
        if bytes[i] == b'@' && bytes[i + 1] == b'@'
            && (i == 0 || bytes[i - 1] == b'\n') {
            if is_hunk_header_at(&bytes[i..]) {
                if starts.len() >= MAX_HUNKS.saturating_add(1) { break; }
                starts.push(i);
                while i < bytes.len() && bytes[i] != b'\n' { i += 1; }
                if i < bytes.len() { i += 1; }
            } else { i += 1; }
        } else { i += 1; }
    }
    starts
}

fn is_hunk_header_at(bytes: &[u8]) -> bool {
    let end = bytes.iter().position(|&b| b == b'\n').unwrap_or(bytes.len());
    let line = match std::str::from_utf8(&bytes[..end]) { Ok(s) => s, Err(_) => return false };
    if !line.starts_with("@@") { return false; }
    let mut parts = line.split_whitespace();
    if parts.next() != Some("@@") { return false; }
    let Some(old) = parts.next() else { return false };
    let Some(new) = parts.next() else { return false };
    if !old.starts_with('-') || !new.starts_with('+') { return false; }
    old[1..].split(',').next().is_some_and(|n| !n.is_empty() && n.bytes().all(|b| b.is_ascii_digit()))
        && new[1..].split(',').next().is_some_and(|n| !n.is_empty() && n.bytes().all(|b| b.is_ascii_digit()))
        && parts.next().is_some_and(|token| token == "@@")
}

fn parse_hunk_header(hunk_text: &str) -> Option<(u32, u32, u32, u32)> {
    let first_line = hunk_text.split('\n').next()?;
    let mut parts = first_line.split_whitespace();
    if parts.next()? != "@@" { return None; }
    let old_part = parts.next()?;
    if !old_part.starts_with('-') { return None; }
    let old_start = old_part[1..].split(',').next()?.parse::<u32>().ok()?;
    let old_count = old_part[1..].split(',').nth(1).and_then(|s| s.parse::<u32>().ok()).unwrap_or(1);
    let new_part = parts.next()?;
    if !new_part.starts_with('+') { return None; }
    let new_start = new_part[1..].split(',').next()?.parse::<u32>().ok()?;
    let new_count = new_part[1..].split(',').nth(1).and_then(|s| s.parse::<u32>().ok()).unwrap_or(1);
    Some((old_start, old_count, new_start, new_count))
}

fn snap_to_char_boundary(s: &str, byte_pos: usize) -> usize {
    let mut pos = byte_pos.min(s.len());
    while pos > 0 && !s.is_char_boundary(pos) { pos -= 1; }
    pos
}

fn gutter_width(lines: &[DiffLine], gutter_padding: usize) -> (usize, usize) {
    let padding_left = 1 + gutter_padding;
    let mut max_line: u32 = 0;
    for line in lines {
        if let Some(n) = line.old_line { max_line = max_line.max(n); }
        if let Some(n) = line.new_line { max_line = max_line.max(n); }
    }
    for line in lines {
        if line.role == DiffLineRole::HunkHeader {
            if let Some((old_last, new_last)) = hunk_header_max_lines(&line.content) {
                max_line = max_line.max(old_last).max(new_last);
            }
        }
    }
    let min_digits = if max_line == 0 { 1 } else { num_digits(max_line) };
    (padding_left, min_digits)
}

fn hunk_header_max_lines(header: &str) -> Option<(u32, u32)> {
    let inner = header.strip_prefix("@@")?;
    let inner = inner.find("@@").map(|end| &inner[..end])?;
    let inner = inner.trim();
    let mut parts = inner.split_whitespace();
    let old_part = parts.next()?.strip_prefix('-')?;
    let new_part = parts.next()?.strip_prefix('+')?;

    let old_start = old_part.split(',').next()?.parse::<u32>().ok()?;
    let old_count = old_part.split(',').nth(1).and_then(|s| s.parse::<u32>().ok()).unwrap_or(1);
    let new_start = new_part.split(',').next()?.parse::<u32>().ok()?;
    let new_count = new_part.split(',').nth(1).and_then(|s| s.parse::<u32>().ok()).unwrap_or(1);

    let old_last = old_start.saturating_add(old_count.saturating_sub(1));
    let new_last = new_start.saturating_add(new_count.saturating_sub(1));
    Some((old_last, new_last))
}

fn num_digits(n: u32) -> usize {
    if n == 0 { 1 } else {
        let mut d = 0;
        let mut v = n;
        while v > 0 { v /= 10; d += 1; }
        d
    }
}

