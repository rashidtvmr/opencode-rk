    fn added_file_patch(count: usize) -> String {
        let mut patch = String::from("--- /dev/null\n+++ b/big.json\n");
        patch.push_str(&format!("@@ -0,0 +1,{count} @@\n"));
        for index in 0..count {
            patch.push_str(&format!("+line {index}\n"));
        }
        patch
    }

    fn added_file_patch_at(path: &str, lines: &[&str]) -> String {
        let mut patch = format!("--- /dev/null\n+++ b/{path}\n");
        patch.push_str(&format!("@@ -0,0 +1,{} @@\n", lines.len()));
        for line in lines {
            patch.push('+');
            patch.push_str(line);
            patch.push('\n');
        }
        patch
    }

